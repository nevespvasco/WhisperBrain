'use strict';
// Echo cancellation for the Linux microphone, done by PipeWire before the audio reaches the speech model.
//
// PipeWire ships `libpipewire-module-echo-cancel` (WebRTC AEC3). Loaded with `monitor.mode = true` it needs no virtual
// sink: it takes the far-end reference from the monitor of the output device and offers a new, echo-cancelled
// microphone source. We load it in a private helper process (`pipewire -c <generated config>`) that exists only while a
// recording runs. Nothing is written to the user's PipeWire configuration, and killing the helper removes the source.
//
// Everything here is injectable (spawn, fs, dump) so the behaviour can be tested against fakes.
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { EventEmitter } = require('node:events');
const { spawn } = require('node:child_process');
const { AudioSource } = require('../audio/source');

const MODULE_FILE = 'libpipewire-module-echo-cancel.so';
const PLUGIN_FILE = 'libspa-aec-webrtc.so';

// ---- detection ----
function libDirs(env = process.env, readdir = (d) => fs.readdirSync(d)) {
  const dirs = ['/usr/lib', '/usr/lib64', '/usr/local/lib', '/usr/local/lib64', '/lib'];
  try { for (const n of readdir('/usr/lib')) if (/-linux-gnu(?:eabihf)?$/.test(n)) dirs.push(`/usr/lib/${n}`); } catch { /* no /usr/lib */ }
  return { dirs, moduleDir: env.PIPEWIRE_MODULE_DIR || null, spaDir: env.SPA_PLUGIN_DIR || null };
}

function find(file, sub, override, dirs, exists) {
  const candidates = [];
  if (override) candidates.push(path.join(override, file), path.join(override, 'aec', file));
  for (const d of dirs) candidates.push(path.join(d, sub, file));
  return candidates.find((p) => exists(p)) || null;
}

// What the machine can do right now. { available, reason, modulePath, pluginPath }
// Needs the module and its WebRTC plugin on disk, a `pipewire` binary to host them, and a module new enough for monitor mode.
async function detectEchoCancel({ env = process.env, exists = fs.existsSync, readFile = fs.readFileSync, readdir, hasCommand } = {}) {
  const { dirs, moduleDir, spaDir } = libDirs(env, readdir);
  const modulePath = find(MODULE_FILE, 'pipewire-0.3', moduleDir, dirs, exists);
  if (!modulePath) return { available: false, reason: 'PipeWire\'s echo-cancel module is not installed (Debian/Ubuntu: pipewire; Fedora: pipewire-plugin-echo-cancel is part of pipewire)' };
  const pluginPath = find(PLUGIN_FILE, 'spa-0.2/aec', spaDir, dirs, exists);
  if (!pluginPath) return { available: false, reason: 'PipeWire\'s WebRTC echo-cancel plugin is missing (Debian/Ubuntu: libspa-0.2-modules)', modulePath };
  let monitorMode = false;
  try { monitorMode = readFile(modulePath).includes('monitor.mode'); } catch { /* unreadable: treat as unsupported */ }
  if (!monitorMode) return { available: false, reason: 'This PipeWire is too old for echo cancellation against the speaker output (needs monitor mode); update PipeWire', modulePath, pluginPath };
  if (hasCommand && !(await hasCommand('pipewire'))) return { available: false, reason: 'The pipewire program is not on PATH', modulePath, pluginPath };
  return { available: true, reason: '', modulePath, pluginPath };
}

// ---- config ----
// SPA-JSON string: quoted, with backslash escapes.
const q = (s) => `"${String(s).replace(/[\\"]/g, '\\$&').replace(/[\u0000-\u001f]/g, ' ')}"`;

// The generated config for one helper. `name` is the node name of the cancelled source (unique per recording).
// captureSink: treat `mic` as an output device and record its monitor (lets tests loop the speakers back without a microphone).
function buildConfig({ name, mic = null, sink = null, noiseSuppression = false, autoGain = false, captureSink = false }) {
  const bool = (v) => (v ? 'true' : 'false');
  return `# generated by WhisperBrain for one recording; deleted when it ends
context.properties = { log.level = 1 }
context.spa-libs = { audio.convert.* = audioconvert/libspa-audioconvert support.* = support/libspa-support }
context.modules = [
  { name = libpipewire-module-rt args = { nice.level = -11 } flags = [ ifexists nofail ] }
  { name = libpipewire-module-protocol-native }
  { name = libpipewire-module-client-node }
  { name = libpipewire-module-adapter }
  { name = libpipewire-module-echo-cancel
    args = {
      library.name = aec/libspa-aec-webrtc
      monitor.mode = true
      aec.args = {
        webrtc.gain_control = ${bool(autoGain)}
        webrtc.noise_suppression = ${bool(noiseSuppression)}
        webrtc.high_pass_filter = true
        webrtc.extended_filter = true
        webrtc.delay_agnostic = true
      }
      capture.props = { node.name = ${q(`${name}.capture`)} ${mic ? `node.target = ${q(mic)}` : ''} ${captureSink ? 'stream.capture.sink = true' : ''} }
      source.props = { node.name = ${q(name)} node.description = ${q('WhisperBrain echo-cancelled microphone')} priority.session = 0 }
      sink.props = { node.name = ${q(`${name}.reference`)} ${sink ? `node.target = ${q(sink)}` : ''} }
    }
  }
]
`;
}

// The helper dies with its parent: the shell watches our pid, so a crashed app cannot leave a stray echo canceller behind.
const WATCHDOG = 'pipewire -c "$1" & pw=$!; trap \'kill $pw 2>/dev/null\' TERM INT HUP EXIT; while kill -0 "$2" 2>/dev/null && kill -0 $pw 2>/dev/null; do sleep 0.5; done';

class EchoCanceller extends EventEmitter {
  // dump(): resolves a parsed pw-dump ({ sources: [{ id }] }) or null. Used to wait until the source node exists.
  constructor({ dump, spawnFn = spawn, fsImpl = fs, tmpdir = os.tmpdir(), pid = process.pid, readyTimeoutMs = 6000, pollMs = 120 } = {}) {
    super();
    Object.assign(this, { dump, spawnFn, fsImpl, tmpdir, pid, readyTimeoutMs, pollMs });
    this.child = null;
    this.dir = null;
    this.name = null;
    this.stopping = false;
    this.ready = false;
    this.exited = null;
  }

  // Resolves with the node name of the echo-cancelled source once PipeWire lists it. Rejects (after cleaning up) otherwise.
  async start({ mic, sink, noiseSuppression, autoGain, captureSink, name = `whisperbrain-aec-${this.pid}-${Date.now().toString(36)}` }) {
    this.name = name;
    this.dir = this.fsImpl.mkdtempSync(path.join(this.tmpdir, 'whisperbrain-aec-'));
    const conf = path.join(this.dir, 'echo-cancel.conf');
    this.fsImpl.writeFileSync(conf, buildConfig({ name, mic, sink, noiseSuppression, autoGain, captureSink }), { mode: 0o600 });
    let stderr = '';
    let child;
    try {
      child = this.spawnFn('sh', ['-c', WATCHDOG, 'whisperbrain-aec', conf, String(this.pid)], { stdio: ['ignore', 'ignore', 'pipe'] });
    } catch (e) { this.cleanup(); throw e; }
    this.child = child;
    child.stderr?.on('data', (d) => { stderr = (stderr + d).slice(-1500); });
    const exited = new Promise((resolve) => {
      child.on('error', (e) => { this.exited = { error: e }; resolve(); });
      child.on('close', (code, signal) => {
        this.exited = { code, signal };
        resolve();
        if (this.ready && !this.stopping) this.emit('lost', new Error(`the echo canceller exited unexpectedly${stderr.trim() ? `: ${stderr.trim()}` : ''}`));
        this.cleanup();
      });
    });
    const deadline = Date.now() + this.readyTimeoutMs;
    try {
      for (;;) {
        if (this.exited) throw new Error(this.exited.error ? this.exited.error.message : `the echo canceller exited (${this.exited.code ?? this.exited.signal})${stderr.trim() ? `: ${stderr.trim()}` : ''}`);
        const d = await Promise.resolve(this.dump()).catch(() => null); // pw-dump can fail while the graph is changing
        if (d?.sources?.some((s) => s.id === name)) break;
        if (Date.now() > deadline) throw new Error(`PipeWire did not offer the echo-cancelled microphone within ${Math.round(this.readyTimeoutMs / 1000)} s${stderr.trim() ? `: ${stderr.trim()}` : ''}`);
        await Promise.race([new Promise((r) => setTimeout(r, this.pollMs)), exited]);
      }
    } catch (e) {
      await this.stop();
      throw e;
    }
    this.ready = true;
    return name;
  }

  // Idempotent. Resolves once the helper is gone and its config deleted.
  stop() {
    if (this.stopPromise) return this.stopPromise;
    this.stopping = true;
    const child = this.child;
    this.stopPromise = new Promise((resolve) => {
      if (!child || this.exited) { this.cleanup(); resolve(); return; }
      const force = setTimeout(() => { try { child.kill('SIGKILL'); } catch { /* gone */ } }, 2000);
      force.unref?.();
      const done = () => { clearTimeout(force); this.cleanup(); resolve(); };
      child.once('close', done);
      child.once('error', done);
      try { child.kill('SIGTERM'); } catch { done(); }
    });
    return this.stopPromise;
  }

  cleanup() {
    if (!this.dir) return;
    try { this.fsImpl.rmSync(this.dir, { recursive: true, force: true }); } catch { /* best effort */ }
    this.dir = null;
  }
}

// The microphone as the rest of the app sees it: PCM from the echo-cancelled source, falling back to the raw microphone
// if the canceller dies or never delivers audio. `aec` is a live status object ({ requested, active, backend, reason }).
class EchoCancelledSource extends AudioSource {
  constructor({ canceller, makeCancelled, makeRaw, aec, firstAudioMs = 5000 }) {
    super();
    Object.assign(this, { canceller, makeCancelled, makeRaw, aec, firstAudioMs });
    this.inner = null;
    this.stopped = false;
    this.heard = false;
    this.timer = null;
    canceller.on('lost', (err) => this.fallBack(err.message));
  }

  wire(src) {
    src.on('pcm', (b) => { if (src !== this.inner) return; this.heard = true; this.emit('pcm', b); });
    src.on('error', (e) => { if (src === this.inner) this.emit('error', e); });
    src.on('end', () => { if (src === this.inner && !this.stopped) this.emit('end'); });
  }

  start() {
    this.inner = this.makeCancelled();
    this.wire(this.inner);
    this.inner.start();
    this.timer = setTimeout(() => { if (!this.heard && !this.stopped) this.fallBack(`no audio from the echo-cancelled microphone after ${Math.round(this.firstAudioMs / 1000)} s`); }, this.firstAudioMs);
    this.timer.unref?.();
  }

  fallBack(reason) {
    if (this.stopped || !this.aec.active) return;
    clearTimeout(this.timer);
    Object.assign(this.aec, { active: false, reason: `${reason}; using the raw microphone` });
    const old = this.inner;
    try { old?.stop(); } catch { /* already gone */ }
    this.canceller.stop();
    this.inner = this.makeRaw();
    this.wire(this.inner);
    this.inner.start();
    this.emit('error', new Error(`echo cancellation stopped (${reason}); recording continues with the raw microphone`));
  }

  stop() {
    this.stopped = true;
    clearTimeout(this.timer);
    try { this.inner?.stop(); } catch { /* already gone */ }
    this.canceller.stop();
  }
}

module.exports = { detectEchoCancel, buildConfig, EchoCanceller, EchoCancelledSource, WATCHDOG };
